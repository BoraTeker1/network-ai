type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends readonly string[]
      ? readonly string[]
      : T[K] extends (...args: infer A) => string
        ? (...args: A) => string
        : DeepStringify<T[K]>;
};

/** Shape shared by both language dictionaries. */
export type Dict = DeepStringify<typeof en>;
